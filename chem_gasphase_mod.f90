SUBROUTINE kppsolve(jvs, x)

! JVS - sparse Jacobian of variables
  REAL(kind=wp):: jvs(lu_nonzero)
! X - Vector for variables
  REAL(kind=wp):: x(nvar)

  x(20) = x(20) - jvs(32) * x(19)
  x(21) = x(21) - jvs(36) * x(18)
  x(23) = x(23) - jvs(43) * x(21) - jvs(44) * x(22)
  x(24) = x(24) - jvs(49) * x(21) - jvs(50) * x(22) - jvs(51) * x(23)
  x(25) = x(25) - jvs(55) * x(18) - jvs(56) * x(22) - jvs(57) * x(23) - jvs(58) * x(24)
  x(26) = x(26) - jvs(61) * x(21) - jvs(62) * x(24) - jvs(63) * x(25)
  x(27) = x(27) - jvs(65) * x(20)
  x(28) = x(28) - jvs(69) * x(19) - jvs(70) * x(27)
  x(29) = x(29) - jvs(75) * x(20) - jvs(76) * x(27) - jvs(77) * x(28)
  x(30) = x(30) - jvs(81) * x(20) - jvs(82) * x(27) - jvs(83) * x(28) - jvs(84) * x(29)
  x(31) = x(31) - jvs(87) * x(29) - jvs(88) * x(30)
  x(31) = x(31) / jvs(89)
  x(30) = (x(30) - jvs(86) * x(31)) /(jvs(85))
  x(29) = (x(29) - jvs(79) * x(30) - jvs(80) * x(31)) /(jvs(78))
  x(28) = (x(28) - jvs(72) * x(29) - jvs(73) * x(30) - jvs(74) * x(31)) /(jvs(71))
  x(27) = (x(27) - jvs(67) * x(28) - jvs(68) * x(30)) /(jvs(66))
  x(26) = x(26) / jvs(64)
  x(25) = (x(25) - jvs(60) * x(26)) /(jvs(59))
  x(24) = (x(24) - jvs(53) * x(25) - jvs(54) * x(26)) /(jvs(52))
  x(23) = (x(23) - jvs(46) * x(24) - jvs(47) * x(25) - jvs(48) * x(26)) /(jvs(45))
  x(22) = (x(22) - jvs(41) * x(23) - jvs(42) * x(24)) /(jvs(40))
  x(21) = (x(21) - jvs(38) * x(24) - jvs(39) * x(25)) /(jvs(37))
  x(20) = (x(20) - jvs(34) * x(28) - jvs(35) * x(30)) /(jvs(33))
  x(19) = (x(19) - jvs(31) * x(28)) /(jvs(30))
  x(18) = (x(18) - jvs(29) * x(25)) /(jvs(28))
  x(17) = (x(17) - jvs(26) * x(28) - jvs(27) * x(29)) /(jvs(25))
  x(16) = (x(16) - jvs(23) * x(20) - jvs(24) * x(30)) /(jvs(22))
  x(15) = (x(15) - jvs(20) * x(19) - jvs(21) * x(28)) /(jvs(19))
  x(14) = (x(14) - jvs(17) * x(21) - jvs(18) * x(24)) /(jvs(16))
  x(13) = (x(13) - jvs(14) * x(23) - jvs(15) * x(25)) /(jvs(13))
  x(12) = x(12) / jvs(12)
  x(11) = x(11) / jvs(11)
  x(10) = x(10) / jvs(10)
  x(9) = x(9) / jvs(9)
  x(8) = x(8) / jvs(8)
  x(7) = x(7) / jvs(7)
  x(6) = x(6) / jvs(6)
  x(5) = x(5) / jvs(5)
  x(4) = x(4) / jvs(4)
  x(3) = x(3) / jvs(3)
  x(2) = x(2) / jvs(2)
  x(1) = x(1) / jvs(1)
      
END SUBROUTINE kppsolve
 
